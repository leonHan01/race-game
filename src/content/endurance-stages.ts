const points = (values: number[][]) => values.map(([x, y, z]) => ({ x, y, z }));
// Distribute the drop by distance so short technical corners do not become steep steps.
function descent(values: number[][], drop: number) {
  const distances = [0];
  for (let i = 1; i < values.length; i++) distances.push(distances[i - 1]
    + Math.hypot(values[i][0] - values[i - 1][0], values[i][1] - values[i - 1][1]));
  return values.map(([x, z], i) => ({ x, y: 45 + drop * (1 - distances[i] / distances[distances.length - 1]), z }));
}

